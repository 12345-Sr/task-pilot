export function getMonthAbbr(lang: string = 'hi', monthIdx: number): string {
  const cfg = LOCALIZED_DATES[lang] || LOCALIZED_DATES.en;
  return cfg.monthsShort[monthIdx] || 'SEP';
}

export function formatLocalizedDate(date: Date, lang: string = 'hi'): string {
  const cfg = LOCALIZED_DATES[lang] || LOCALIZED_DATES.hi;
  const day = cfg.days[date.getDay()];
  const month = cfg.months[date.getMonth()];
  return `${day}, ${date.getDate()} ${month}`;
}

