export type LanguageCode = keyof typeof translations;

export function t(lang: string = 'hi', key: string): string {
  const dict = translations[lang] || translations.hi;
  if (dict && dict[key]) {
    return dict[key];
  }
  if (translations.hi && translations.hi[key]) {
    return translations.hi[key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return key;
}

export function getTranslation(lang: string = 'hi') {
  const base = translations.hi;
  const target = translations[lang] || {};
  return { ...base, ...target };
}

export default translations;
